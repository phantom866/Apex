const SEVERITY_COLORS: Record<string, string> = {
  critical: 'text-rose-400 bg-rose-950/40 border-rose-700/50',
  high:     'text-amber-400 bg-amber-950/40 border-amber-700/50',
  medium:   'text-blue-400  bg-blue-950/40  border-blue-700/50',
  low:      'text-slate-400 bg-slate-800/60  border-slate-700/50',
};

const LEVEL_COLORS: Record<string, string> = {
  fatal: 'text-rose-400',
  error: 'text-red-400',
  warn:  'text-amber-400',
  info:  'text-slate-400',
  debug: 'text-slate-500',
};

function formatTs(iso: string): string {
  try { return new Date(iso).toLocaleTimeString(); } catch { return iso; }
}

function reportToMarkdown(r: InvestigationReport): string {
  const lines: string[] = [
    `# APEX Incident Report — ${r.title}`,
    `\n> **Generated:** ${new Date(r.generatedAt).toLocaleString()}  |  **Report ID:** ${r.id}`,
    r.isSimulated ? '\n> ⚠️ **SIMULATED DATA — these logs are fictional for demo purposes.**' : '',
    `\n## Summary\n${r.summary}`,
    `\n## Severity\n**${r.severity.toUpperCase()}**`,
    `\n## Probable Root Cause\n${r.probableRootCause}`,
    `\n## Affected Services\n${r.affectedServices.map(s => `- ${s}`).join('\n')}`,
    `\n## Cascade Chain\n${r.cascade.map(n =>
      `### ${n.isRootCause ? '🔴 ROOT CAUSE — ' : ''}${n.service}\n` +
      (n.downstreamServices.length ? `Downstream: ${n.downstreamServices.join(' → ')}\n` : '') +
      n.incidents.map(i => `- [${i.severity.toUpperCase()}] ${i.title}`).join('\n')
    ).join('\n\n')}`,
    `\n## Chronological Evidence\n| Time | Service | Level | Message |\n|---|---|---|---|\n${
      r.chronologicalEvidence.map(e =>
        `| ${formatTs(e.timestamp)} | ${e.service} | ${e.level.toUpperCase()} | ${e.message.replace(/\|/g, '\\|')} |`
      ).join('\n')
    }`,
    `\n## Remediation Steps\n${r.remediationSteps.map((s, i) => `${i + 1}. ${s}`).join('\n')}`,
    `\n---\n*Report generated by APEX NOVA — Autonomous Platform for Engineering eXcellence*`,
  ];
  return lines.filter(Boolean).join('\n');
}

function downloadFile(content: string, filename: string, mime: string) {
  const blob = new Blob([content], { type: mime });
  const url  = URL.createObjectURL(blob);
  const a    = document.createElement('a');
  a.href = url; a.download = filename; a.click();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}

